----------------------TABELE ASOCIATIVE--------------------
-- ANALIZE_PERSONAL

CREATE TABLE ANALIZE_PERSONAL (
ID_MILITAR INT REFERENCES PERS_MIL (ID_MILITAR), COD_ANALIZA INT REFERENCES ANALIZE (COD_ANALIZA), PRIMARY KEY (ID_MILITAR, COD_ANALIZA)
);

-- ANALIZE_CERCETARE
CREATE TABLE ANALIZE_CERCETARE (
COD_ANALIZA INT REFERENCES ANALIZE (COD_ANALIZA), ID_PROIECT INT REFERENCES CERCETARE (ID_PROIECT), PRIMARY KEY (COD_ANALIZA, ID_PROIECT)
);

-- MEDICAMENT_TRATAMENT
CREATE TABLE MEDICAMENT_TRATAMENT (
ID_MED INT REFERENCES MEDICAMENT (ID_MED), COD_TRAT INT REFERENCES TRATAMENT (COD_TRAT), PRIMARY KEY (ID_MED, COD_TRAT)
);

