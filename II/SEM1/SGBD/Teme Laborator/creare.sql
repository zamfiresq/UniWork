--TRATAMENT

CREATE SEQUENCE TRATAMENT_COD_TRAT_SEQ
START WITH 1
MAXVALUE 9999999
NOCACHE NOCYCLE;


CREATE TABLE TRATAMENT (
    COD_TRAT INT CONSTRAINT TRATAMENT_COD_TRAT_PK PRIMARY KEY,
    COD_PACIENT INT CONSTRAINT TRATAMENT_COD_PACIENT_FK REFERENCES PACIENT(COD_PACIENT) ON DELETE CASCADE
);


--PERSONAL MILITAR

CREATE SEQUENCE PERS_MIL_ID_MILITAR_SEQ
START WITH 1
MAXVALUE 9999999
NOCACHE NOCYCLE;


CREATE TABLE PERS_MIL(
    ID_MILITAR INT
                    CONSTRAINT PERS_MIL_ID_MILITAR_PK PRIMARY KEY,
    ID_CATEGORIE INT
                    CONSTRAINT PERS_MIL_ID_CATEGORIE_FK REFERENCES CATEGORIE(ID_CATEGORIE) ON DELETE CASCADE,
    NUME VARCHAR2(25)
                    CONSTRAINT PERS_MIL_NUME_NN NOT NULL,
    PRENUME VARCHAR2(30)
                    CONSTRAINT PERS_MIL_PRENUME_NN NOT NULL,
    GRAD_MILITAR VARCHAR2(15)
                             CONSTRAINT PERS_MIL_GRAD_MILITAR_NN NOT NULL,
    SALARIU NUMBER(8,2)
                             CONSTRAINT PERS_MIL_SALARIU_CK CHECK ( SALARIU >= 5000 ),
    DATA_ANGAJARE DATE,
    EMAIL VARCHAR2(25)
);


