
-------------------CREATE TABLE-----------------------

--PACIENT

CREATE SEQUENCE PACIENT_COD_PACIENT_SEQ
START WITH 1
MAXVALUE 9999999
NOCACHE NOCYCLE;


CREATE TABLE PACIENT(
                        COD_PACIENT INT
                            CONSTRAINT PACIENT_COD_PACIENT_PK PRIMARY KEY,
                        NUME VARCHAR2(25)
                            CONSTRAINT PACIENT_NUME_NN NOT NULL,
                        PRENUME VARCHAR2(30)
                            CONSTRAINT PACIENT_PRENUME_NN NOT NULL,
                        SEX VARCHAR2(10)
                            CONSTRAINT PACIENT_SEX_NN NOT NULL,
                        CNP VARCHAR2(20)
                            CONSTRAINT PACIENT_CNP_NN NOT NULL,
                        NR_TELEFON VARCHAR2(15),
                        ADRESA VARCHAR2(40)
);


